# Коробки пам'яті для кожного гравця
potoчний_режим = {}  # Тут бот пам'ятатиме, який режим ти обрала
potoчна_загадка = {} # Тут бот пам'ятатиме поточне питання
поточна_відповідь = {} # Тут бот пам'ятатиме правильну відповідь

def nova_gra(message):
    chat_id = message.chat.id
    
    # Вибираємо випадкову пару країна-столиця
    kraina = random.choice(list(baza_krain.keys()))
    stolitsia = baza_krain[kraina]
    
    # Перевіряємо, який режим обрано. Якщо нічого не обрано — ставимо стандартний
    if chat_id not in potoчний_режим:
        potoчний_режим[chat_id] = "mode_capital"
        
    if potoчний_режим[chat_id] == "mode_capital":
        potoчна_загадка[chat_id] = kraina
        поточна_відповідь[chat_id] = stolitsia
        pytannya_text = f"welhe столиця\n\n <b>{kraina}</b>"
    else:
        potoчна_загадка[chat_id] = stolitsia
        поточна_відповідь[chat_id] = kraina
        pytannya_text = f"welhe країна?\n\n🏛️ <b>{stolitsia}</b>"
    
    # Кнопки для гри
    knopky = types.InlineKeyboardMarkup()
    btn_vidpovid = types.InlineKeyboardButton(text="я дібіл", callback_data="show")
    btn_dali = types.InlineKeyboardButton(text="давай дальше", callback_data="next")
    btn_menu = types.InlineKeyboardButton(text=" інший режим", callback_data="change_mode")
    knopky.add(btn_vidpovid, btn_dali)
    knopky.add(btn_menu)
    
    bot.send_message(chat_id, pytannya_text, parse_mode="HTML", reply_markup=knopky)

# Показує меню вибору режиму
def pokazaty_menu_rezhymiv(chat_id):
    menu_knopky = types.InlineKeyboardMarkup()
    btn_c = types.InlineKeyboardButton(text="країна", callback_data="set_mode_capital")
    btn_c2 = types.InlineKeyboardButton(text="кепітал", callback_data="set_mode_country")
    menu_knopky.add(btn_c)
    menu_knopky.add(btn_c2)
    bot.send_message(chat_id, "обирай чого душа бажає", reply_markup=menu_knopky)

@bot.message_handler(commands=['start'])
def start_message(message):
    bot.send_message(message.chat.id, " давай брат покажи на що  здатен!! ⚔️")
    pokazaty_menu_rezhymiv(message.chat.id)

@bot.callback_query_handler(func=lambda call: True)
def callback_worker(call):
    chat_id = call.message.chat.id
    
    if call.data == "set_mode_capital":
        potoчний_режим[chat_id] = "mode_capital"
        bot.send_message(chat_id, "путі назад немає,удачі 🐲")
        nova_gra(call.message)
        
    elif call.data == "set_mode_country":
        potoчний_режим[chat_id] = "mode_country"
        bot.send_message(chat_id, "путі назад немає,удачі 🐲")
        nova_gra(call.message)
        
    elif call.data == "change_mode":
        pokazaty_menu_rezhymiv(chat_id)
        
    elif call.data == "show":
        vidpovid = поточна_відповідь.get(chat_id, "505 /start")
        bot.send_message(chat_id, f"дібіл, ета -   <b>{vidpovid}</b>", parse_mode="HTML")
        nova_gra(call.message)
        
    elif call.data == "next":
        nova_gra(call.message)
